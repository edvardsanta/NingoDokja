"""Application Knowledge store backed by PostgreSQL and pgvector.

The fixed service-owned schema is separate from other domains. Existing SQLite
files are never opened or imported by service startup.
"""

from __future__ import annotations

import hashlib
import json
import re

import numpy as np
import psycopg
from chunker import Chunk
from metadata import encode_metadata
from pgvector.psycopg import register_vector
from psycopg.rows import dict_row
from store import _now


class PostgresStore:
    backend = "postgres"

    def __init__(self, dsn: str):
        if not dsn.strip():
            raise ValueError("KNOWLEDGE_POSTGRES_DSN is required for postgres storage")
        try:
            self.conn = psycopg.connect(
                dsn, autocommit=True, row_factory=dict_row, connect_timeout=10
            )
        except psycopg.Error:
            raise RuntimeError("PostgreSQL Knowledge connection failed") from None
        try:
            self.conn.execute("SET statement_timeout = '30s'")
            self.conn.execute("SET lock_timeout = '5s'")
            self._migrate()
            register_vector(self.conn)
        except Exception:
            self.conn.close()
            raise
        self.version = 0

    def close(self):
        self.conn.close()

    def _migrate(self):
        with self.conn.transaction():
            self.conn.execute("SELECT pg_advisory_xact_lock(91350401)")
            self.conn.execute(
                "CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public"
            )
            self.conn.execute(
                "CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public"
            )
            self.conn.execute("CREATE SCHEMA IF NOT EXISTS dokja_knowledge")
            self.conn.execute("SET search_path TO dokja_knowledge, public")
            self.conn.execute(
                "CREATE TABLE IF NOT EXISTS schema_version "
                "(singleton boolean PRIMARY KEY CHECK (singleton), version integer NOT NULL)"
            )
            current = self.conn.execute(
                "SELECT version FROM schema_version WHERE singleton"
            ).fetchone()
            if current and current["version"] != 1:
                raise RuntimeError(
                    "PostgreSQL Knowledge schema is not supported by this build"
                )
            if current:
                return
            self.conn.execute("""
                CREATE TEXT SEARCH CONFIGURATION knowledge_search (COPY = pg_catalog.simple);
                ALTER TEXT SEARCH CONFIGURATION knowledge_search
                    ALTER MAPPING FOR hword, hword_part, word
                    WITH public.unaccent, pg_catalog.simple;
                CREATE TABLE documents (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source_id text NOT NULL UNIQUE, title text NOT NULL,
                    kind text NOT NULL, source_ref text NOT NULL, tags text NOT NULL,
                    content_hash text NOT NULL, created_at text NOT NULL,
                    updated_at text NOT NULL
                );
                CREATE TABLE chunks (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    document_id bigint NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
                    position integer NOT NULL, heading text NOT NULL, text text NOT NULL,
                    embedding vector, embed_model text,
                    search_text tsvector GENERATED ALWAYS AS
                        (to_tsvector('dokja_knowledge.knowledge_search', text || ' ' || heading)) STORED,
                    UNIQUE(document_id, position)
                );
                CREATE INDEX chunks_by_document ON chunks(document_id, position);
                CREATE INDEX chunks_keywords ON chunks USING gin(search_text);
                CREATE TABLE document_metadata (
                    document_id bigint PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE,
                    metadata text NOT NULL
                );
                INSERT INTO schema_version VALUES (true, 1);
            """)

    def get_document(self, source_id):
        return self.conn.execute(
            "SELECT * FROM documents WHERE source_id = %s", (source_id,)
        ).fetchone()

    def replace_document(
        self,
        source_id,
        title,
        kind,
        source_ref,
        tags,
        content_hash,
        chunks: list[Chunk],
        metadata="{}",
    ):
        stamp = _now()
        with self.conn.transaction():
            # Serialize same-source replacement, including the first insertion.
            self.conn.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))", (source_id,)
            )
            existing = self.get_document(source_id)
            if existing is None:
                row = self.conn.execute(
                    """
                    INSERT INTO documents(source_id, title, kind, source_ref, tags,
                                          content_hash, created_at, updated_at)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s) RETURNING id
                """,
                    (
                        source_id,
                        title,
                        kind,
                        source_ref,
                        tags,
                        content_hash,
                        stamp,
                        stamp,
                    ),
                ).fetchone()
                document_id, created = row["id"], True
            else:
                document_id, created = existing["id"], False
                self.conn.execute(
                    "SELECT id FROM documents WHERE id = %s FOR UPDATE", (document_id,)
                )
                self.conn.execute(
                    "DELETE FROM chunks WHERE document_id = %s", (document_id,)
                )
                self.conn.execute(
                    """
                    UPDATE documents SET title=%s, kind=%s, source_ref=%s, tags=%s,
                                         content_hash=%s, updated_at=%s WHERE id=%s
                """,
                    (title, kind, source_ref, tags, content_hash, stamp, document_id),
                )
            with self.conn.cursor() as cursor:
                cursor.executemany(
                    "INSERT INTO chunks(document_id, position, heading, text) VALUES (%s, %s, %s, %s)",
                    [(document_id, c.position, c.heading, c.text) for c in chunks],
                )
            self._write_metadata(document_id, metadata)
        self.version += 1
        return document_id, created

    def get_metadata(self, document_id):
        row = self.conn.execute(
            "SELECT metadata FROM document_metadata WHERE document_id = %s",
            (document_id,),
        ).fetchone()
        return row["metadata"] if row else "{}"

    def _write_metadata(self, document_id, metadata):
        self.conn.execute(
            """
            INSERT INTO document_metadata VALUES (%s, %s)
            ON CONFLICT(document_id) DO UPDATE SET metadata = excluded.metadata
        """,
            (document_id, metadata),
        )

    def update_metadata(self, document_id, metadata):
        with self.conn.transaction():
            self.conn.execute(
                "SELECT id FROM documents WHERE id = %s FOR UPDATE", (document_id,)
            )
            if self.get_metadata(document_id) == metadata:
                return False
            self._write_metadata(document_id, metadata)
            self.conn.execute(
                "UPDATE documents SET updated_at=%s WHERE id=%s", (_now(), document_id)
            )
        return True

    def metadata_snapshot(self, source_id):
        row = self.conn.execute(
            """
            SELECT d.source_id, d.title, d.content_hash, COALESCE(m.metadata, '{}') AS metadata
            FROM documents d LEFT JOIN document_metadata m ON m.document_id = d.id
            WHERE d.source_id = %s
        """,
            (source_id,),
        ).fetchone()
        if row is None:
            raise ValueError("knowledge document not found")
        metadata = json.loads(row["metadata"])
        identity = json.dumps(
            [row["source_id"], row["content_hash"], metadata],
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
        return {
            "source_id": row["source_id"],
            "title": row["title"],
            "metadata": metadata,
            "revision": hashlib.sha256(identity.encode()).hexdigest(),
        }

    def classification_sample(self, source_id):
        with self.conn.transaction():
            self.conn.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ")
            snapshot = self.metadata_snapshot(source_id)
            document = self.get_document(source_id)
            parts, remaining = [], 16000
            for row in self.conn.execute(
                "SELECT substr(text, 1, 16000) AS text FROM chunks WHERE document_id=%s ORDER BY position",
                (document["id"],),
            ):
                part = row["text"][:remaining]
                parts.append(part)
                remaining -= len(part) + 2
                if remaining <= 0:
                    break
        return {
            **snapshot,
            "text": "\n\n".join(parts)[:16000],
            "representation": "chunk_reconstruction",
        }

    def patch_metadata(self, source_id, patch, revision):
        with self.conn.transaction():
            self.conn.execute(
                "SELECT id FROM documents WHERE source_id=%s FOR UPDATE", (source_id,)
            )
            snapshot = self.metadata_snapshot(source_id)
            if snapshot["revision"] != revision:
                raise ValueError(
                    "classification_conflict: document changed; reload the questions"
                )
            merged = {**snapshot["metadata"], **patch}
            encoded = encode_metadata(merged)
            changed = merged != snapshot["metadata"]
            if changed:
                document = self.get_document(source_id)
                self._write_metadata(document["id"], encoded)
                self.conn.execute(
                    "UPDATE documents SET updated_at=%s WHERE id=%s",
                    (_now(), document["id"]),
                )
            result = self.metadata_snapshot(source_id)
        return {**result, "metadata_changed": changed, "changed": False}

    def delete_document(self, source_id):
        row = self.conn.execute(
            "DELETE FROM documents WHERE source_id=%s RETURNING id", (source_id,)
        ).fetchone()
        self.version += int(row is not None)
        return row is not None

    def list_documents(self, limit, offset, kind="", exclude=(), source_id=""):
        return self.conn.execute(
            """
            SELECT d.*, COALESCE(m.metadata, '{}') AS metadata, COUNT(c.id) AS chunks,
                   COUNT(c.embedding) AS embedded
            FROM documents d LEFT JOIN chunks c ON c.document_id = d.id
            LEFT JOIN document_metadata m ON m.document_id = d.id
            WHERE (%s = '' OR d.kind = %s) AND NOT (d.kind = ANY(%s::text[]))
              AND (%s = '' OR d.source_id = %s)
            GROUP BY d.id, m.metadata ORDER BY d.updated_at DESC, d.id DESC LIMIT %s OFFSET %s
        """,
            (kind, kind, list(exclude), source_id, source_id, limit, offset),
        ).fetchall()

    def document_count(self, kind="", exclude=(), source_id=""):
        return self.conn.execute(
            """
            SELECT COUNT(*) AS count FROM documents
            WHERE (%s = '' OR kind = %s) AND NOT (kind = ANY(%s::text[]))
              AND (%s = '' OR source_id = %s)
        """,
            (kind, kind, list(exclude), source_id, source_id),
        ).fetchone()["count"]

    def document_text(self, document_id):
        rows = self.conn.execute(
            "SELECT heading, text FROM chunks WHERE document_id=%s ORDER BY position",
            (document_id,),
        ).fetchall()
        return "\n\n".join(
            "\n".join(part for part in (r["heading"], r["text"]) if part) for r in rows
        )

    def stats(self, model):
        return self.conn.execute(
            """
            SELECT (SELECT COUNT(*) FROM documents) AS documents,
                   (SELECT COUNT(*) FROM chunks) AS chunks,
                   (SELECT COUNT(*) FROM chunks WHERE embedding IS NOT NULL AND embed_model=%s) AS embedded
        """,
            (model,),
        ).fetchone()

    def chunks_needing_embedding(self, model, limit=None):
        return self.conn.execute(
            """
            SELECT c.id, c.text, c.heading, d.title FROM chunks c
            JOIN documents d ON d.id = c.document_id
            WHERE c.embedding IS NULL OR c.embed_model IS DISTINCT FROM %s ORDER BY c.id LIMIT %s
        """,
            (model, limit),
        ).fetchall()

    def set_embeddings(self, chunk_ids, matrix, model):
        if len(chunk_ids) != len(matrix):
            raise ValueError("embedding count does not match chunks")
        with self.conn.transaction(), self.conn.cursor() as cursor:
            cursor.executemany(
                "UPDATE chunks SET embedding=%s, embed_model=%s WHERE id=%s",
                [
                    (np.asarray(v, dtype=np.float32), model, chunk_id)
                    for chunk_id, v in zip(chunk_ids, matrix)
                ],
            )
        self.version += 1

    def vector_search(self, vector, model, kind, limit):
        vector = np.asarray(vector, dtype=np.float32)
        rows = self.conn.execute(
            """
            WITH eligible AS MATERIALIZED (
                SELECT c.id, c.embedding FROM chunks c JOIN documents d ON d.id=c.document_id
                WHERE c.embedding IS NOT NULL AND c.embed_model=%s
                  AND vector_dims(c.embedding)=%s AND (%s = '' OR d.kind=%s)
            )
            SELECT id, CASE WHEN vector_norm(embedding)=0 OR %s THEN 0
                            ELSE 1 - (embedding <=> %s) END AS score FROM eligible
            ORDER BY score DESC, id LIMIT %s
        """,
            (
                model,
                len(vector),
                kind,
                kind,
                bool(np.linalg.norm(vector) == 0),
                vector,
                limit,
            ),
        ).fetchall()
        return {row["id"]: float(row["score"]) for row in rows}

    def keyword_search(self, fts_query, limit, kind=""):
        # The caller supplies quoted OR terms, not arbitrary SQL/tsquery syntax.
        terms = re.findall(r'"([^"\\]+)"', fts_query)
        if not terms:
            return []
        query = " | ".join("'" + term.replace("'", "''") + "'" for term in terms)
        rows = self.conn.execute(
            """
            SELECT c.id, -ts_rank_cd(c.search_text, to_tsquery('dokja_knowledge.knowledge_search', %s)) AS score
            FROM chunks c JOIN documents d ON d.id=c.document_id
            WHERE c.search_text @@ to_tsquery('dokja_knowledge.knowledge_search', %s) AND (%s = '' OR d.kind=%s)
            ORDER BY score, c.id LIMIT %s
        """,
            (query, query, kind, kind, limit),
        ).fetchall()
        return [(row["id"], row["score"]) for row in rows]

    def chunks_by_ids(self, ids):
        if not ids:
            return {}
        rows = self.conn.execute(
            """
            SELECT c.id, c.position, c.heading, c.text, d.source_id, d.title,
                   d.kind, d.source_ref, d.tags, COALESCE(m.metadata, '{}') AS metadata
            FROM chunks c JOIN documents d ON d.id=c.document_id
            LEFT JOIN document_metadata m ON m.document_id=d.id WHERE c.id = ANY(%s::bigint[])
        """,
            (list(ids),),
        ).fetchall()
        return {row["id"]: row for row in rows}
